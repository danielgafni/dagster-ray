import tomllib
from itertools import chain

from packaging.requirements import Requirement

from dagster_ray_dev.matrix import Matrix

COMPATIBILITY_MATRIX_PATH = "docs/compatibility-matrix.md"

# KubeRay features with a higher minimum than the oldest tested KubeRay version, as API reference links
KUBERAY_FEATURES = [
    ("[`RayClusterSpec.auth_options`][dagster_ray.kuberay.configs.RayClusterSpec.auth_options]", "1.5.2"),
    ("[`AuthOptions.secret_name`][dagster_ray.kuberay.configs.AuthOptions.secret_name]", "1.6.0"),
    ("[`RayClusterSpec.upgrade_strategy`][dagster_ray.kuberay.configs.RayClusterSpec.upgrade_strategy]", "1.6.0"),
    (
        "[`RayJobSpec.pre_running_deadline_seconds`][dagster_ray.kuberay.configs.RayJobSpec.pre_running_deadline_seconds]",
        "1.6.0",
    ),
]


def _specifier(requirements: list[str], name: str) -> str:
    return next(str(r.specifier) for r in map(Requirement, requirements) if r.name == name)


def _versions(matrix: Matrix, component: str) -> list[str]:
    versions = dict.fromkeys(getattr(v, component) for v in matrix.versions)
    return sorted(versions, key=lambda v: tuple(map(int, v.split("."))), reverse=True)


def _tested(matrix: Matrix, component: str) -> str:
    return ", ".join(_versions(matrix, component))


def compatibility_matrix(pyproject_toml: str, matrix: Matrix) -> str:
    """The compatibility page: supported versions from pyproject.toml and test-matrix.toml."""
    project = tomllib.loads(pyproject_toml)["project"]
    extras = list(chain.from_iterable(project["optional-dependencies"].values()))
    rows = [
        ("Python", f"`{project['requires-python']}`", _tested(matrix, "python")),
        ("Ray", f"`{_specifier(extras, 'ray')}`", _tested(matrix, "ray")),
        ("Dagster", f"`{_specifier(project['dependencies'], 'dagster')}`", _tested(matrix, "dagster")),
        ("KubeRay", f"`>={_versions(matrix, 'kuberay')[-1]}`", _tested(matrix, "kuberay")),
    ]
    table = "\n".join(f"| {name} | {supported} | {tested} |" for name, supported, tested in rows)
    features = "\n".join(f"| {feature} | {version} |" for feature, version in KUBERAY_FEATURES)
    return f"""---
title: "Compatibility Matrix"
description: "The Python, Ray, Dagster and KubeRay versions dagster-ray supports, and the ones its CI tests."
---

<!-- Generated by `dagger generate` from pyproject.toml and the Dagger module's test-matrix.toml. -->

# Compatibility Matrix

| Dependency | Supported | Tested |
|---|---|---|
{table}

KubeRay is tested with Kubernetes {matrix.kubernetes}.

## KubeRay Features

These features need a newer KubeRay than the minimum:

| Feature | KubeRay |
|---|---|
{features}
"""
